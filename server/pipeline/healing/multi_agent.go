package healing

import (
	"context"
	"fmt"
	"strings"
)

// CandidatePatch is a proposed code fix generated by the developer persona.
type CandidatePatch struct {
	StepName        string `json:"step_name"`
	ProposedDiff    string `json:"proposed_diff"`
	DiagnosticRCA   string `json:"diagnostic_rca"`
	ConfidenceScore float64 `json:"confidence_score"`
}

// DualTurnAuditResult is the outcome of the Clinical Safety Auditor's cross-examination.
type DualTurnAuditResult struct {
	Approved          bool        `json:"approved"`
	HazardLevel       HazardLevel `json:"hazard_level"`
	AuditorNotes      string      `json:"auditor_notes"`
	DetectedViolations []string   `json:"detected_violations"`
	ApprovedCandidate *CandidatePatch `json:"approved_candidate,omitempty"`
}

// DualAgentAuditor handles the two-turn cross-examination of automated fixes.
type DualAgentAuditor interface {
	AuditCandidatePatch(ctx context.Context, patch CandidatePatch) (DualTurnAuditResult, error)
}

// ClinicalSafetyMultiAgentAuditor runs Turn 2 (Clinical Safety Auditor) on Turn 1 (Dev Engineer).
type ClinicalSafetyMultiAgentAuditor struct{}

// NewClinicalSafetyMultiAgentAuditor creates a new dual-turn auditor.
func NewClinicalSafetyMultiAgentAuditor() *ClinicalSafetyMultiAgentAuditor {
	return &ClinicalSafetyMultiAgentAuditor{}
}

// AuditCandidatePatch scrutinizes the developer's candidate patch for clinical regressions and safety violations.
func (a *ClinicalSafetyMultiAgentAuditor) AuditCandidatePatch(ctx context.Context, patch CandidatePatch) (DualTurnAuditResult, error) {
	result := DualTurnAuditResult{
		ApprovedCandidate: &patch,
		HazardLevel:       HazardNegligible,
	}

	diffLower := strings.ToLower(patch.ProposedDiff)
	var violations []string

	// Rule 1: Safety Assertions relaxation check (e.g. removing assert, reducing thresholds)
	lines := strings.Split(patch.ProposedDiff, "\n")
	for _, rawLine := range lines {
		trimmed := strings.TrimSpace(rawLine)
		if strings.HasPrefix(trimmed, "-") && !strings.HasPrefix(trimmed, "---") {
			removedContent := strings.ToLower(strings.TrimSpace(strings.TrimPrefix(trimmed, "-")))
			if strings.HasPrefix(removedContent, "assert") ||
				strings.HasPrefix(removedContent, "expect") ||
				strings.HasPrefix(removedContent, "require") ||
				strings.Contains(removedContent, "assert.") {
				violations = append(violations, "Attempted relaxation or deletion of test assertion in candidate patch")
				result.HazardLevel = HazardCritical
				break
			}
		}
	}

	// Rule 2: Clinical Threshold tampering check (e.g. adjusting vital thresholds, sensitivity bounds)
	thresholdKeywords := []string{
		"threshold",
		"cutoff",
		"sensitivity",
		"specificity",
		"systolic",
		"diastolic",
		"sp02",
		"spo2",
		"heartrate",
		"temperature",
	}

	for _, kw := range thresholdKeywords {
		if strings.Contains(diffLower, "-") && strings.Contains(diffLower, kw) {
			violations = append(violations, fmt.Sprintf("Candidate patch alters critical clinical parameter: %s", kw))
			result.HazardLevel = HazardCritical
		}
	}

	// Rule 3: Zero-Mock violation check
	if strings.Contains(diffLower, "mock") || strings.Contains(diffLower, "fake") || strings.Contains(diffLower, "stub") {
		violations = append(violations, "Candidate patch introduces prohibited mock or stub logic into clinical verification")
		result.HazardLevel = HazardMajor
	}

	// If any violation is found, turn 2 REJECTS the patch
	if len(violations) > 0 {
		result.Approved = false
		result.DetectedViolations = violations
		result.AuditorNotes = fmt.Sprintf("Turn 2 (Clinical Safety Auditor) REJECTED candidate patch due to %d safety violations: %s",
			len(violations), strings.Join(violations, "; "))
		return result, nil
	}

	// Turn 2 APPROVES the patch
	result.Approved = true
	result.HazardLevel = HazardNegligible
	result.AuditorNotes = "Turn 2 (Clinical Safety Auditor) PASSED: Patch introduces no assertion relaxations, threshold alterations, or mock dependencies."
	return result, nil
}
