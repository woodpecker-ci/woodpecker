const (
	testModel = `package model

import "example.com/errors"

type Status string //	@name	Status

type Kind int

// Repo is a repository.
type Repo struct {
	ID     int64  ` + "`" + `json:"id"    xorm:"pk autoincr 'id'"` + "`" + `
	Secret string ` + "`" + `json:"-"     xorm:"secret"` + "`" + `
	// Owner is who the repo belongs to.
	Owner  string            ` + "`" + `json:"owner" xorm:"owner"` + "`" + `
	State  Status            ` + "`" + `json:"state"` + "`" + `
	Kind   Kind              ` + "`" + `json:"kind"` + "`" + `
	Last   *APIPipeline      ` + "`" + `json:"last,omitempty"` + "`" + `
	Labels map[string]Status ` + "`" + `json:"labels"` + "`" + `
	Errors []*errors.Problem ` + "`" + `json:"errors"` + "`" + `
	Data   any               ` + "`" + `json:"data"` + "`" + `
	hidden int
}

type Pipeline struct {
	Number int64 ` + "`" + `json:"number"` + "`" + `
}

// APIPipeline adds what only the API has.
type APIPipeline struct {
	*Pipeline
	Extra bool ` + "`" + `json:"extra"` + "`" + ` // only in the API
} //	@name	Pipeline

type Unused struct {
	ID int64 ` + "`" + `json:"id"` + "`" + `
}
`

	testClient = `package woodpecker

type Kind int

type Problem struct{}
`

	testWant = `// Code generated by woodpecker-go/typegen from the server models; DO NOT EDIT.

package woodpecker

type Pipeline struct {
	Number int64 ` + "`" + `json:"number"` + "`" + `
	Extra  bool  ` + "`" + `json:"extra"` + "`" + ` // only in the API
}

// Repo is a repository.
type Repo struct {
	ID int64 ` + "`" + `json:"id"` + "`" + `
	// Owner is who the repo belongs to.
	Owner  string            ` + "`" + `json:"owner"` + "`" + `
	State  string            ` + "`" + `json:"state"` + "`" + `
	Kind   Kind              ` + "`" + `json:"kind"` + "`" + `
	Last   *Pipeline         ` + "`" + `json:"last,omitempty"` + "`" + `
	Labels map[string]string ` + "`" + `json:"labels"` + "`" + `
	Errors []*Problem        ` + "`" + `json:"errors"` + "`" + `
	Data   any               ` + "`" + `json:"data"` + "`" + `
}
`
)

func testDirs(t *testing.T, model, client string) (modelDir, clientDir string) {
	t.Helper()
	modelDir, clientDir = t.TempDir(), t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(modelDir, "model.go"), []byte(model), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(clientDir, "types.go"), []byte(client), 0o600))
	// what an earlier run wrote must not count as written by hand
	require.NoError(t, os.WriteFile(filepath.Join(clientDir, "out.go"), []byte("package woodpecker\n\ntype Status string\n"), 0o600))
	return modelDir, clientDir
}

func TestGenerate(t *testing.T) {
	t.Run("types", func(t *testing.T) {
		modelDir, clientDir := testDirs(t, testModel, testClient)

		got, err := generate(modelDir, clientDir, "out.go", []string{"Repo"})
		require.NoError(t, err)
		assert.Equal(t, testWant, string(got))
	})

	errTests := []struct {
		name   string
		model  string
		client string
		roots  []string
		err    string
	}{
		{
			name:  "unknown root",
			model: "package model\n",
			roots: []string{"Repo"},
			err:   "unknown type Repo",
		},
		{
			name:  "type of another package the client does not have",
			model: "package model\n\ntype Repo struct {\n\tErr errors.Problem `json:\"err\"`\n}\n",
			roots: []string{"Repo"},
			err:   "Repo.Err: the client has no type Problem",
		},
		{
			name:  "struct without a name",
			model: "package model\n\ntype Repo struct {\n\tStats struct{ N int } `json:\"stats\"`\n}\n",
			roots: []string{"Repo"},
			err:   "Repo.Stats: unsupported type struct{N int}",
		},
		{
			name:  "two types with the same name",
			model: "package model\n\ntype Repo struct{}\n\ntype APIRepo struct{} //\t@name\tRepo\n",
			roots: []string{"Repo", "APIRepo"},
			err:   "APIRepo and Repo are both named Repo",
		},
	}
	for _, tt := range errTests {
		t.Run(tt.name, func(t *testing.T) {
			modelDir, clientDir := testDirs(t, tt.model, "package woodpecker\n"+tt.client)

			_, err := generate(modelDir, clientDir, "out.go", tt.roots)
			assert.ErrorContains(t, err, tt.err)
		})
	}
}
