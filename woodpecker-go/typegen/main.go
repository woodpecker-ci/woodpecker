// Command typegen writes the types of the go client from the models of the
// server, so the client always knows every field the API has.
//
// It copies the given model structs and every struct they use, with the json
// tags only. A model is named like its swag "@name". Fields of embedded
// structs are added to the struct itself. A type the client declares by hand
// under the same name is used as is, any other named type that is no struct
// is replaced by what it is made of, e.g. a string.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"maps"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

func main() {
	modelDir := flag.String("model", "", "directory of the server models")
	clientDir := flag.String("client", ".", "directory of the client")
	out := flag.String("out", "types_generated.go", "file in the client directory to write")
	flag.Parse()

	src, err := generate(*modelDir, *clientDir, *out, flag.Args())
	if err == nil {
		err = os.WriteFile(filepath.Join(*clientDir, *out), src, 0o600)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

var swagName = regexp.MustCompile(`@name\s+(\w+)`)

type generator struct {
	// types of the server models by name
	model map[string]*ast.TypeSpec
	// docs of the server models by name
	docs map[string]*ast.CommentGroup
	// names of the types the client declares by hand
	client map[string]bool
	// models still to write
	todo []string
}

// generate returns the source of the client types for the models named by
// roots and all structs they use. The file out in clientDir is ignored, as it
// is what an earlier run wrote.
func generate(modelDir, clientDir, out string, roots []string) ([]byte, error) {
	g := &generator{
		model:  make(map[string]*ast.TypeSpec),
		docs:   make(map[string]*ast.CommentGroup),
		client: make(map[string]bool),
		todo:   slices.Clone(roots),
	}

	err := eachType(modelDir, "", func(decl *ast.GenDecl, spec *ast.TypeSpec) {
		g.model[spec.Name.Name] = spec
		g.docs[spec.Name.Name] = spec.Doc
		if spec.Doc == nil {
			g.docs[spec.Name.Name] = decl.Doc
		}
	})
	if err != nil {
		return nil, err
	}
	err = eachType(clientDir, out, func(_ *ast.GenDecl, spec *ast.TypeSpec) {
		g.client[spec.Name.Name] = true
	})
	if err != nil {
		return nil, err
	}

	// source and model of each written type by its name in the client
	sources := make(map[string]string)
	models := make(map[string]string)
	for done := make(map[string]bool); len(g.todo) > 0; {
		name := g.todo[0]
		g.todo = g.todo[1:]
		if done[name] {
			continue
		}
		done[name] = true

		spec, ok := g.model[name]
		if !ok {
			return nil, fmt.Errorf("unknown type %s", name)
		}
		clientName := g.clientName(spec)
		if other, ok := models[clientName]; ok {
			return nil, fmt.Errorf("%s and %s are both named %s", name, other, clientName)
		}
		models[clientName] = name

		src, err := g.structSource(name, clientName)
		if err != nil {
			return nil, err
		}
		sources[clientName] = src
	}

	var b strings.Builder
	b.WriteString("// Code generated by woodpecker-go/typegen from the server models; DO NOT EDIT.\n\npackage woodpecker\n")
	for _, name := range slices.Sorted(maps.Keys(sources)) {
		b.WriteString("\n" + sources[name])
	}
	return format.Source([]byte(b.String()))
}

// eachType calls fn for every type declared in the go files of dir, tests and
// the file named skip left out.
func eachType(dir, skip string, fn func(*ast.GenDecl, *ast.TypeSpec)) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	fileSet := token.NewFileSet()
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || name == skip || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fileSet, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				fn(gen, spec.(*ast.TypeSpec)) //nolint:forcetypeassert
			}
		}
	}
	return nil
}

// clientName returns how the client names a model: by its swag name if it
// has one.
func (g *generator) clientName(spec *ast.TypeSpec) string {
	if m := swagName.FindStringSubmatch(spec.Comment.Text()); m != nil {
		return m[1]
	}
	return spec.Name.Name
}

// structSource returns the declaration of the model struct name as the client
// type clientName.
func (g *generator) structSource(name, clientName string) (string, error) {
	st, ok := g.model[name].Type.(*ast.StructType)
	if !ok {
		return "", fmt.Errorf("%s is no struct", name)
	}

	var b strings.Builder
	// a doc that starts with another name describes the model, not the client type
	if doc := g.docs[name]; strings.HasPrefix(doc.Text(), clientName+" ") {
		writeComment(&b, doc)
	}
	b.WriteString("type " + clientName + " struct {\n")
	if err := g.writeFields(&b, name, st); err != nil {
		return "", err
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// writeFields writes the fields of the model struct name that are part of
// its JSON, the ones of embedded structs included.
func (g *generator) writeFields(b *strings.Builder, name string, st *ast.StructType) error {
	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			ident, _ := field.Type.(*ast.Ident)
			if star, ok := field.Type.(*ast.StarExpr); ok {
				ident, _ = star.X.(*ast.Ident)
			}
			if ident == nil || g.model[ident.Name] == nil {
				return fmt.Errorf("%s: unsupported embedded type %s", name, types.ExprString(field.Type))
			}
			est, ok := g.model[ident.Name].Type.(*ast.StructType)
			if !ok {
				return fmt.Errorf("%s: embedded type %s is no struct", name, ident.Name)
			}
			if err := g.writeFields(b, ident.Name, est); err != nil {
				return err
			}
			continue
		}

		var tag string
		if field.Tag != nil {
			value, err := strconv.Unquote(field.Tag.Value)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", name, field.Names[0].Name, err)
			}
			if json := reflect.StructTag(value).Get("json"); json == "-" {
				continue
			} else if json != "" {
				tag = " `json:\"" + json + "\"`"
			}
		}

		for _, fieldName := range field.Names {
			if !fieldName.IsExported() {
				continue
			}
			typ, err := g.typeSource(field.Type)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", name, fieldName.Name, err)
			}
			writeComment(b, field.Doc)
			b.WriteString(fieldName.Name + " " + typ + tag)
			if field.Comment != nil {
				b.WriteString(" " + field.Comment.List[0].Text)
			}
			b.WriteString("\n")
		}
	}
	return nil
}

func writeComment(b *strings.Builder, doc *ast.CommentGroup) {
	if doc == nil {
		return
	}
	for _, line := range doc.List {
		b.WriteString(line.Text + "\n")
	}
}

// typeSource returns the type of a model field as the client has it.
func (g *generator) typeSource(expr ast.Expr) (string, error) {
	switch t := expr.(type) {
	case *ast.Ident:
		return g.namedSource(t.Name)
	case *ast.StarExpr:
		elem, err := g.typeSource(t.X)
		return "*" + elem, err
	case *ast.ArrayType:
		if t.Len != nil {
			break
		}
		elem, err := g.typeSource(t.Elt)
		return "[]" + elem, err
	case *ast.MapType:
		key, err := g.typeSource(t.Key)
		if err != nil {
			return "", err
		}
		value, err := g.typeSource(t.Value)
		return "map[" + key + "]" + value, err
	case *ast.SelectorExpr:
		// a type of another package: the client has to declare it by hand
		if !g.client[t.Sel.Name] {
			return "", fmt.Errorf("the client has no type %s", t.Sel.Name)
		}
		return t.Sel.Name, nil
	}
	return "", fmt.Errorf("unsupported type %s", types.ExprString(expr))
}

// namedSource returns the type the client uses for the type name of the
// models, and notes a struct to be written.
func (g *generator) namedSource(name string) (string, error) {
	spec, ok := g.model[name]
	if !ok {
		if types.Universe.Lookup(name) == nil {
			return "", fmt.Errorf("unknown type %s", name)
		}
		return name, nil
	}

	clientName := g.clientName(spec)
	if g.client[clientName] {
		return clientName, nil
	}
	if _, ok := spec.Type.(*ast.StructType); ok {
		g.todo = append(g.todo, name)
		return clientName, nil
	}
	return g.typeSource(spec.Type)
}
